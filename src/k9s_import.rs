#[derive(Debug, Default, Deserialize)]
#[serde(default)]
struct AliasFile {
    aliases: BTreeMap<String, serde_yaml::Value>,
}

impl AliasFile {
    /// The alias map. Older k9s releases wrote it nested, as
    /// `aliases: {aliases: {...}}`.
    fn entries(&self) -> BTreeMap<String, String> {
        let flat = match self.aliases.get("aliases") {
            Some(serde_yaml::Value::Mapping(inner)) => inner
                .iter()
                .filter_map(|(k, v)| Some((k.as_str()?.to_string(), v.clone())))
                .collect(),
            _ => self.aliases.clone(),
        };
        flat.into_iter()
            .filter_map(|(k, v)| Some((k, v.as_str()?.to_string())))
            .collect()
    }
}

