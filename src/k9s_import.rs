//! `sofka import k9s`: carry a k9s setup over to sofka.
//!
//! The importer reads k9s's own files (`config.yaml`, `aliases.yaml`,
//! `plugins.yaml` and the `plugins/` directory, `hotkeys.yaml`, `views.yaml`,
//! and the per-context `clusters/<cluster>/<context>/` files) and writes sofka
//! YAML next to the user's config: one drop-in, `conf.d/00-k9s.yaml`, plus one
//! override file per k9s context that carried a real setting. It never edits a
//! file it did not generate, and a setting the base sofka config already sets
//! keeps the user's value. Everything that does not translate is reported, so
//! nothing is dropped silently.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::Deserialize;
use toml::{Table, Value};

/// First line of every generated file; also how a re-import recognizes the
/// files it may replace.
pub const MARKER: &str = "# Generated by `sofka import k9s`.";

const DROPIN: &str = "conf.d/00-k9s.yaml";

#[derive(clap::Args, Debug, Clone)]
pub struct ImportArgs {
    #[command(subcommand)]
    pub source: ImportSource,
}

#[derive(clap::Subcommand, Debug, Clone)]
pub enum ImportSource {
    /// Convert k9s config, aliases, plugins, hotkeys, views, and per-context settings.
    K9s {
        /// k9s config directory. Default: $K9S_CONFIG_DIR, then the k9s XDG location.
        #[arg(long, value_name = "DIR", value_hint = clap::ValueHint::DirPath)]
        from: Option<PathBuf>,
        /// Print the files that would be written, without writing them.
        #[arg(long)]
        dry_run: bool,
        /// Replace files written by an earlier import.
        #[arg(long)]
        force: bool,
    },
}

pub fn run(args: &ImportArgs) -> Result<(), String> {
    let ImportSource::K9s {
        from,
        dry_run,
        force,
    } = &args.source;
    let sources = match from {
        Some(dir) => Sources::at(dir)?,
        None => Sources::locate()?,
    };
    let (loader, _) = crate::config::ConfigLoader::load();
    let dir = loader
        .dir()
        .ok_or("cannot determine the sofka config directory: set XDG_CONFIG_HOME or HOME")?
        .to_path_buf();
    let user = UserConfig::read(&loader);
    let plan = plan(&sources, &user);
    for line in apply(&plan, &dir, *dry_run, *force)? {
        println!("{line}");
    }
    Ok(())
}

/// Where the k9s files live: the config directory (`config.yaml`,
/// `aliases.yaml`, …) and the directories that may hold `clusters/` and
/// `plugins/`, in k9s's own lookup order.
#[derive(Debug, Clone, PartialEq)]
pub struct Sources {
    pub config: PathBuf,
    pub data: Vec<PathBuf>,
}

#[derive(Debug, Clone, Copy, PartialEq)]
enum Platform {
    Linux,
    MacOs,
    Windows,
}

const CONFIG_FILES: &[&str] = &[
    "config.yaml",
    "aliases.yaml",
    "plugins.yaml",
    "hotkeys.yaml",
    "views.yaml",
];

impl Sources {
    /// Read everything from one directory, as k9s does with `K9S_CONFIG_DIR`.
    pub fn at(dir: &Path) -> Result<Self, String> {
        if !dir.is_dir() {
            return Err(format!("{} is not a directory", dir.display()));
        }
        Ok(Self {
            config: dir.to_path_buf(),
            data: vec![dir.to_path_buf()],
        })
    }

    /// Find the k9s directories the way k9s does (adrg/xdg), so the import
    /// reads the same files k9s would.
    pub fn locate() -> Result<Self, String> {
        let platform = if cfg!(target_os = "macos") {
            Platform::MacOs
        } else if cfg!(windows) {
            Platform::Windows
        } else {
            Platform::Linux
        };
        let home = crate::config::home_dir().map(PathBuf::from);
        let (config, data) = candidates(platform, |name| std::env::var_os(name), home);
        let found = config.iter().find(|dir| holds_k9s_config(dir));
        let Some(found) = found else {
            let searched: Vec<String> = config.iter().map(|d| d.display().to_string()).collect();
            return Err(format!(
                "no k9s configuration found (searched {}); pass --from DIR",
                searched.join(", ")
            ));
        };
        let mut dirs = vec![found.clone()];
        dirs.extend(data.into_iter().filter(|d| d.is_dir() && d != found));
        Ok(Self {
            config: found.clone(),
            data: dirs,
        })
    }
}

fn holds_k9s_config(dir: &Path) -> bool {
    CONFIG_FILES.iter().any(|f| dir.join(f).is_file())
        || dir.join("clusters").is_dir()
        || dir.join("plugins").is_dir()
}

/// The user's own sofka settings around the import, as sofka merges them:
/// `before` is what the drop-in is merged over (the base config and drop-ins
/// that sort earlier), `after` the drop-ins merged after it.
#[derive(Debug, Default)]
pub struct UserConfig {
    pub before: Option<Value>,
    pub after: Vec<Value>,
}

impl UserConfig {
    fn read(loader: &crate::config::ConfigLoader) -> Self {
        let dropin = Path::new(DROPIN).file_name();
        let mut before = loader.base_value().cloned().into_iter().collect::<Vec<_>>();
        let mut after = Vec::new();
        for path in loader.dropin_paths() {
            if generated(&path) {
                continue;
            }
            let Ok(Some(layer)) = crate::config::read_layer(&path) else {
                continue;
            };
            if path.file_name() < dropin {
                before.push(layer);
            } else {
                after.push(layer);
            }
        }
        Self {
            before: (!before.is_empty()).then(|| crate::config::merge_layers(before)),
            after,
        }
    }
}

/// Candidate config and data directories, most specific first.
fn candidates(
    platform: Platform,
    var: impl Fn(&str) -> Option<std::ffi::OsString>,
    home: Option<PathBuf>,
) -> (Vec<PathBuf>, Vec<PathBuf>) {
    let var = |name: &str| var(name).filter(|v| !v.is_empty()).map(PathBuf::from);
    if let Some(dir) = var("K9S_CONFIG_DIR") {
        return (vec![dir.clone()], vec![dir]);
    }
    let mut config = Vec::new();
    let mut data = Vec::new();
    if let Some(dir) = var("XDG_CONFIG_HOME") {
        config.push(dir.join("k9s"));
    }
    if let Some(dir) = var("XDG_DATA_HOME") {
        data.push(dir.join("k9s"));
    }
    match platform {
        Platform::Windows => {
            if let Some(dir) = var("LOCALAPPDATA") {
                config.push(dir.join("k9s"));
                data.push(dir.join("k9s"));
            }
        }
        Platform::MacOs => {
            if let Some(home) = &home {
                let dir = home.join("Library").join("Application Support").join("k9s");
                config.push(dir.clone());
                data.push(dir);
            }
        }
        Platform::Linux => {}
    }
    if let Some(home) = &home {
        config.push(home.join(".config").join("k9s"));
        data.push(home.join(".local").join("share").join("k9s"));
    }
    config.dedup();
    data.dedup();
    (config, data)
}

/// One file the import produces, relative to the sofka config directory.
#[derive(Debug, Clone)]
pub struct Output {
    pub path: PathBuf,
    pub doc: Table,
    /// Where the settings came from, for the report.
    pub label: String,
}

#[derive(Debug, Default)]
pub struct Plan {
    pub source: PathBuf,
    pub outputs: Vec<Output>,
    /// k9s settings that were not imported, with the reason.
    pub skipped: Vec<String>,
    /// Imported settings dropped because the base sofka config already sets them.
    pub kept: Vec<String>,
    /// The user's settings merged with the imported global ones, as a context
    /// override file inherits them.
    pub effective: Option<Value>,
    /// k9s files that exist but could not be read. Their settings are missing
    /// from the plan, not removed, so earlier imports of them are kept.
    pub unreadable: Vec<PathBuf>,
}

