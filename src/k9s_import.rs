/// Drop imported settings the base sofka config already sets: the drop-in is
/// merged over the base, so leaving them in would override the user's own
/// choice. Plugins merge by name; bookmarks, a list a drop-in would replace,
/// are carried over from the base so both survive.
fn keep_base(doc: &mut Table, base: &Table, kept: &mut Vec<String>, skipped: &mut Vec<String>) {
    let names = |v: Option<&Value>, field: &str| -> Vec<String> {
        v.and_then(Value::as_array)
            .map(|a| {
                a.iter()
                    .filter_map(|p| p.get(field).and_then(Value::as_str).map(String::from))
                    .collect()
            })
            .unwrap_or_default()
    };
    if let Some(Value::Array(list)) = doc.get_mut("plugins") {
        let base_names = names(base.get("plugins"), "name");
        list.retain(|p| {
            let name = p.get("name").and_then(Value::as_str).unwrap_or_default();
            let clash = base_names.iter().any(|n| n == name);
            if clash {
                kept.push(format!("plugin {name:?}"));
            }
            !clash
        });
        if list.is_empty() {
            doc.remove("plugins");
        }
    }
    if let (Some(Value::Array(own)), Some(Value::Array(theirs))) =
        (doc.get("bookmarks"), base.get("bookmarks"))
    {
        let base_names = names(base.get("bookmarks"), "name");
        let base_keys = names(base.get("bookmarks"), "key");
        let mut merged = theirs.clone();
        for b in own {
            let name = b.get("name").and_then(Value::as_str).unwrap_or_default();
            let key = b.get("key").and_then(Value::as_str);
            if base_names.iter().any(|n| n == name)
                || key.is_some_and(|k| base_keys.iter().any(|b| b == k))
            {
                skipped.push(format!(
                    "hotkey {name:?}: your sofka config has a bookmark with that name or key"
                ));
            } else {
                merged.push(b.clone());
            }
        }
        doc.insert("bookmarks".into(), Value::Array(merged));
    }
    let mut base = base.clone();
    for key in ["plugins", "bookmarks", "plugins_merge", "plugins_remove"] {
        base.remove(key);
    }
    keep_tables(doc, &base, "", kept);
}

fn keep_tables(doc: &mut Table, base: &Table, path: &str, kept: &mut Vec<String>) {
    let keys: Vec<String> = doc.keys().cloned().collect();
    for key in keys {
        let Some(theirs) = base.get(&key) else {
            continue;
        };
        let here = if path.is_empty() {
            key.clone()
        } else {
            format!("{path}.{key}")
        };
        match (doc.get_mut(&key), theirs) {
            (Some(Value::Table(ours)), Value::Table(theirs)) => {
                keep_tables(ours, theirs, &here, kept);
                if ours.is_empty() {
                    doc.remove(&key);
                }
            }
            _ => {
                doc.remove(&key);
                kept.push(here);
            }
        }
    }
}

