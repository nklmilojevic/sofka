const SHELLS: &[&str] = &["sh", "bash", "zsh", "dash", "ksh", "fish"];

fn convert_plugins(plugins: &[(String, K9sPlugin)], doc: &mut Table, skipped: &mut Vec<String>) {
    for (name, plugin) in plugins {
        match convert_plugin(name, plugin) {
            Ok((p, notes)) => {
                skipped.extend(notes.into_iter().map(|n| format!("plugin {name:?}: {n}")));
                doc.entry("plugins")
                    .or_insert_with(|| Value::Array(Vec::new()))
                    .as_array_mut()
                    .expect("importer arrays are only created here")
                    .retain(|v| v.get("name").and_then(Value::as_str) != Some(name));
                if let Some(Value::Array(list)) = doc.get_mut("plugins") {
                    list.push(Value::Table(p));
                }
            }
            Err(e) => skipped.push(format!("plugin {name:?}: {e}")),
        }
    }
}

/// Convert one plugin, or explain why it cannot work in sofka. The notes are
/// imported-but-different behaviours worth a line in the report.
fn convert_plugin(name: &str, p: &K9sPlugin) -> Result<(Table, Vec<String>), String> {
    let mut notes = Vec::new();
    if !p.pipes.is_empty() {
        return Err("`pipes` has no sofka equivalent; chain the commands in a shell script".into());
    }
    let key = chord(&p.short_cut)
        .ok_or_else(|| format!("key {:?} has no sofka equivalent", p.short_cut))?;
    if p.command.trim().is_empty() {
        return Err("no command".into());
    }

    let mut scopes = Vec::new();
    let mut all = p.scopes.is_empty();
    let mut containers = false;
    for scope in &p.scopes {
        let s = scope.trim().to_ascii_lowercase();
        if s == "all" {
            all = true;
        } else if s == "containers" || s == "co" {
            containers = true;
        } else {
            // sofka matches scopes against the bare plural, whatever the group.
            let plural = s.rsplit('/').next().unwrap_or(&s).to_string();
            let plural = crate::k8s::ALIASES
                .iter()
                .find(|(a, _)| *a == plural)
                .map(|(_, t)| (*t).to_string())
                .unwrap_or(plural);
            if !scopes.contains(&plural) {
                scopes.push(plural);
            }
        }
    }
    if containers {
        if !all && scopes.is_empty() {
            return Err("sofka plugins cannot target the k9s containers view".into());
        }
        notes.push("the containers scope does not exist in sofka; dropped".into());
    }

    let input_names: Vec<String> = p.inputs.iter().map(|i| i.name.clone()).collect();
    let mut args = Vec::new();
    let mut leftover = Vec::new();
    for arg in &p.args {
        let arg = yaml_string(arg);
        args.push(rewrite_arg(&arg, &input_names, &mut leftover)?);
    }
    leftover.sort();
    leftover.dedup();
    if !leftover.is_empty() {
        let shell = Path::new(p.command.trim())
            .file_name()
            .and_then(|s| s.to_str())
            .is_some_and(|c| SHELLS.contains(&c));
        let source = if shell {
            "left to the shell environment"
        } else {
            "passed through unexpanded"
        };
        notes.push(format!(
            "{} {source}; sofka has no such placeholder",
            leftover.join(", ")
        ));
    }

    let mut out = Table::new();
    out.insert("name".into(), name.into());
    out.insert("key".into(), key.into());
    out.insert("command".into(), p.command.trim().into());
    out.insert(
        "args".into(),
        Value::Array(args.into_iter().map(Value::from).collect()),
    );
    if !all {
        out.insert(
            "scopes".into(),
            Value::Array(scopes.into_iter().map(Value::from).collect()),
        );
    }
    // k9s hides a `dangerous` plugin in read-only mode and runs every other
    // one; sofka's `mutating` flag is that same switch.
    out.insert("mutating".into(), p.dangerous.into());
    if p.confirm.unwrap_or(!p.inputs.is_empty()) {
        out.insert("confirm".into(), true.into());
    }
    if p.background {
        out.insert("output".into(), "background".into());
    }
    if !p.inputs.is_empty() {
        let mut inputs = Table::new();
        for input in &p.inputs {
            let mut spec = Table::new();
            let kind = match input.kind.as_str() {
                "bool" => "boolean",
                _ => "string",
            };
            spec.insert("type".into(), kind.into());
            let default = input.default.as_ref().map(yaml_string);
            match default {
                Some(d) => {
                    spec.insert("default".into(), d.into());
                }
                None if !input.required => {
                    // An optional input still needs a value sofka accepts:
                    // a dropdown's first option, or an empty string.
                    let default = match (kind, input.options.first()) {
                        ("boolean", _) => "false".to_string(),
                        _ if input.kind == "dropdown" => {
                            input.options.first().cloned().unwrap_or_default()
                        }
                        _ => String::new(),
                    };
                    spec.insert("default".into(), default.into());
                }
                None => {}
            }
            if input.kind == "dropdown" && !input.options.is_empty() {
                spec.insert(
                    "choices".into(),
                    Value::Array(input.options.iter().cloned().map(Value::from).collect()),
                );
            }
            inputs.insert(input.name.clone(), Value::Table(spec));
        }
        out.insert("inputs".into(), Value::Table(inputs));
        out.insert("prompt".into(), "always".into());
    }
    if p.overrides {
        notes.push(format!(
            "k9s let it override a built-in key; in sofka a built-in key on {:?} wins until you rebind it under [keys]",
            p.short_cut
        ));
    }
    Ok((out, notes))
}

fn yaml_string(v: &serde_yaml::Value) -> String {
    match v {
        serde_yaml::Value::String(s) => s.clone(),
        serde_yaml::Value::Number(n) => n.to_string(),
        serde_yaml::Value::Bool(b) => b.to_string(),
        other => serde_yaml::to_string(other)
            .unwrap_or_default()
            .trim()
            .to_string(),
    }
}

/// Rewrite k9s's `$VAR` / `${VAR}` placeholders (case-insensitive in k9s) to
/// sofka's spelling. Fails for a placeholder a plugin cannot run without;
/// records the rest, which k9s would also leave alone or fill from the
/// kubeconfig, in `leftover`.
fn rewrite_arg(arg: &str, inputs: &[String], leftover: &mut Vec<String>) -> Result<String, String> {
    use std::sync::LazyLock;
    static RX: LazyLock<regex::Regex> = LazyLock::new(|| {
        regex::Regex::new(r"\$(!?)([\w\-]+)|\$\{(!?)([\w\-%/: ]+)\}").expect("valid regex")
    });

    let mut err = None;
    let whole = RX.find(arg).is_some_and(|m| m.as_str() == arg);
    let out = RX.replace_all(arg, |caps: &regex::Captures| {
        let raw = &caps[0];
        let inverse = caps.get(1).or(caps.get(3)).is_some_and(|m| !m.is_empty());
        let key = caps.get(2).or(caps.get(4)).map_or("", |m| m.as_str());
        let upper = key.to_ascii_uppercase();
        if inverse {
            err = Some(format!(
                "{raw}: inverted placeholders have no sofka equivalent"
            ));
            return raw.to_string();
        }
        match upper.as_str() {
            "NAMESPACE" | "NAME" | "CONTEXT" | "CLUSTER" | "FILTER" => format!("${upper}"),
            "RESOURCE_NAME" => "$RESOURCE".into(),
            "RESOURCE_GROUP" => "$GROUP".into(),
            "RESOURCE_VERSION" => "$VERSION".into(),
            "POD" => {
                err = Some(
                    "$POD comes from the k9s containers view, which sofka plugins cannot target"
                        .into(),
                );
                raw.to_string()
            }
            u if u.starts_with("COL-") => {
                err = Some(format!("{raw}: sofka plugins cannot read table cells"));
                raw.to_string()
            }
            u if u.starts_with("INPUT_") => {
                let name = &key["INPUT_".len()..];
                match inputs.iter().find(|i| i.eq_ignore_ascii_case(name)) {
                    Some(input) if whole => format!("${{input.{input}}}"),
                    Some(_) => {
                        err = Some(format!(
                            "{raw}: sofka passes inputs as whole arguments, not inside a string"
                        ));
                        raw.to_string()
                    }
                    None => {
                        leftover.push(raw.to_string());
                        raw.to_string()
                    }
                }
            }
            "KUBECONFIG" | "USER" | "GROUPS" => {
                leftover.push(format!("${upper}"));
                raw.to_string()
            }
            _ => raw.to_string(),
        }
    });
    match err {
        Some(e) => Err(e),
        None => Ok(out.into_owned()),
    }
}

