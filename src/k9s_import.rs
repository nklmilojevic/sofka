/// k9s names resources as `group/version/plural`, `version/plural`, or a bare
/// name; sofka resolves `plural.group` or a bare name.
fn alias_target(target: &str) -> String {
    let target = target.trim().trim_start_matches(':').to_ascii_lowercase();
    let parts: Vec<&str> = target.split('/').collect();
    match parts.as_slice() {
        [group, _version, plural] if !group.is_empty() => format!("{plural}.{group}"),
        [_version, plural] => (*plural).to_string(),
        _ => target,
    }
}

fn convert_aliases(aliases: &BTreeMap<String, String>, doc: &mut Table, skipped: &mut Vec<String>) {
    for (alias, target) in aliases {
        let alias = alias.trim().to_ascii_lowercase();
        if alias.is_empty() {
            continue;
        }
        if target.split_whitespace().count() > 1 {
            // `pp: pods kube-system app=web` carries a destination, which is
            // what a sofka bookmark is.
            match navigation(target) {
                Ok(nav) => push_bookmark(doc, nav.bookmark(&alias, None)),
                Err(e) => skipped.push(format!("alias {alias:?}: {e}")),
            }
            continue;
        }
        let target = alias_target(target);
        if crate::k8s::ALIASES
            .iter()
            .any(|(a, t)| *a == alias && *t == target)
            || alias == target
        {
            continue;
        }
        table(doc, "aliases").insert(alias, target.into());
    }
}

fn convert_hotkeys(hotkeys: &BTreeMap<String, Hotkey>, doc: &mut Table, skipped: &mut Vec<String>) {
    for (name, hk) in hotkeys {
        let Some(key) = chord(&hk.short_cut) else {
            skipped.push(format!(
                "hotkey {name:?}: key {:?} has no sofka equivalent",
                hk.short_cut
            ));
            continue;
        };
        match navigation(&hk.command) {
            Ok(nav) => push_bookmark(doc, nav.bookmark(name, Some(key))),
            Err(e) => skipped.push(format!("hotkey {name:?}: {e}")),
        }
    }
}

fn push_bookmark(doc: &mut Table, bookmark: Table) {
    doc.entry("bookmarks")
        .or_insert_with(|| Value::Array(Vec::new()))
        .as_array_mut()
        .expect("importer arrays are only created here")
        .push(Value::Table(bookmark));
}

#[derive(Debug, Default, PartialEq)]
struct Navigation {
    resource: String,
    namespace: Option<String>,
    context: Option<String>,
    filter: Option<String>,
    view: Option<&'static str>,
}

impl Navigation {
    fn bookmark(&self, name: &str, key: Option<String>) -> Table {
        let mut b = Table::new();
        if let Some(key) = key {
            b.insert("key".into(), key.into());
        }
        b.insert("name".into(), name.into());
        b.insert("resource".into(), self.resource.clone().into());
        for (field, value) in [
            ("namespace", &self.namespace),
            ("context", &self.context),
            ("filter", &self.filter),
        ] {
            if let Some(v) = value {
                b.insert(field.into(), v.clone().into());
            }
        }
        if let Some(view) = self.view {
            b.insert("view".into(), view.into());
        }
        b
    }
}

/// Parse a k9s command line (`dp`, `pods kube-system`, `po app=web @prod`,
/// `xray deploy`) into a bookmark destination.
fn navigation(command: &str) -> Result<Navigation, String> {
    let mut words = command
        .trim()
        .trim_start_matches(':')
        .split_whitespace()
        .peekable();
    let first = words.next().ok_or("empty command")?.to_ascii_lowercase();
    let mut nav = Navigation::default();
    match first.as_str() {
        "x" | "xray" => {
            nav.view = Some("xray");
            nav.resource = alias_target(words.next().ok_or("xray needs a resource")?);
        }
        "pu" | "pulse" | "pulses" => {
            nav.view = Some("pulse");
            nav.resource = "pods".into();
        }
        "ctx" | "context" | "contexts" | "q" | "q!" | "quit" | "help" | "?" | "sd"
        | "screendump" | "be" | "benchmark" | "benchmarks" | "pop" | "popeye" | "dir" => {
            return Err(format!("k9s command {first:?} has no bookmark equivalent"));
        }
        _ => nav.resource = alias_target(&first),
    }
    for word in words {
        if let Some(ctx) = word.strip_prefix('@') {
            nav.context = Some(ctx.to_string());
        } else if word.contains('=') {
            nav.filter = Some(format!("-l {word}"));
        } else if nav.namespace.is_none() && !word.starts_with(['-', '/']) {
            nav.namespace = Some(word.to_string());
        } else {
            return Err(format!("cannot translate {word:?} in {command:?}"));
        }
    }
    Ok(nav)
}

/// Translate a k9s key name (tcell's `KeyNames` plus k9s's own) into a sofka
/// chord. k9s `Shift-1` is the `!` key on a US layout, and so on.
fn chord(k9s: &str) -> Option<String> {
    let k9s = k9s.trim();
    let out = if let Some(rest) = k9s.strip_prefix("Shift-") {
        let mut chars = rest.chars();
        let (c, None) = (chars.next()?, chars.next()) else {
            return None;
        };
        if c.is_ascii_alphabetic() {
            c.to_ascii_uppercase().to_string()
        } else {
            let digit = c.to_digit(10)? as usize;
            ")!@#$%^&*(".chars().nth(digit)?.to_string()
        }
    } else if let Some(rest) = k9s.strip_prefix("Ctrl-") {
        format!("ctrl-{}", rest.to_ascii_lowercase())
    } else if k9s.chars().count() == 1 {
        k9s.to_string()
    } else {
        match k9s.to_ascii_lowercase().as_str() {
            "backspace2" => "backspace".into(),
            other => other.to_string(),
        }
    };
    crate::keys::KeyChord::parse(&out).ok().map(|_| out)
}

