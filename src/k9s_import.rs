/// Read the k9s files under `src` and build the sofka files to write.
/// Settings the user's sofka config already sets win.
pub fn plan(src: &Sources, user: &UserConfig) -> Plan {
    let mut plan = Plan {
        source: src.config.clone(),
        ..Plan::default()
    };
    let skipped = &mut plan.skipped;
    let mut unreadable = Vec::new();
    let mut doc = Table::new();

    let main: Option<MainFile> = read(&src.config.join("config.yaml"), skipped, &mut unreadable);
    let main = main.unwrap_or_default().k9s;
    convert_settings(&main, &mut doc, skipped);

    if let Some(file) =
        read::<AliasFile>(&src.config.join("aliases.yaml"), skipped, &mut unreadable)
    {
        convert_aliases(&file.entries(), &mut doc, skipped);
    }

    let mut plugins = read_plugins(&src.config.join("plugins.yaml"), skipped, &mut unreadable);
    let mut plugin_dirs: Vec<PathBuf> = src.data.iter().map(|d| d.join("plugins")).collect();
    plugin_dirs.insert(0, src.config.join("plugins"));
    plugin_dirs.dedup();
    for dir in plugin_dirs {
        for path in yaml_files(&dir) {
            plugins.extend(read_plugins(&path, skipped, &mut unreadable));
        }
    }
    convert_plugins(&plugins, &mut doc, skipped);

    if let Some(file) =
        read::<HotkeyFile>(&src.config.join("hotkeys.yaml"), skipped, &mut unreadable)
    {
        convert_hotkeys(&file.hot_keys, &mut doc, skipped);
    }

    if let Some(file) = read::<ViewFile>(&src.config.join("views.yaml"), skipped, &mut unreadable) {
        convert_views(&file.views, &mut doc, skipped);
    }

    if let Some(base) = user.before.as_ref().and_then(Value::as_table) {
        keep_base(&mut doc, base, &mut plan.kept, skipped);
    }
    if doc.contains_key("plugins") {
        doc.insert("plugins_merge".into(), "name".into());
    }

    let effective = crate::config::merge_layers(
        user.before
            .iter()
            .cloned()
            .chain([Value::Table(doc.clone())])
            .chain(user.after.iter().cloned()),
    );
    let global_bookmarks = effective.get("bookmarks").cloned();
    plan.effective = Some(effective);
    let global_skin = main.ui.skin.clone().filter(|s| !s.is_empty());
    if !doc.is_empty() {
        plan.outputs.push(Output {
            path: PathBuf::from(DROPIN),
            doc,
            label: "global settings".into(),
        });
    }

    let clusters = src
        .data
        .iter()
        .map(|d| d.join("clusters"))
        .find(|d| d.is_dir());
    if let Some(clusters) = clusters {
        for (cluster, context, dir) in context_dirs(&clusters) {
            let ctx = ContextInput {
                cluster: &cluster,
                context: &context,
                dir: &dir,
                read_only: main.read_only.unwrap_or(false),
                skin: global_skin.as_deref(),
                bookmarks: global_bookmarks.as_ref(),
            };
            if let Some(out) = convert_context(&ctx, skipped, &mut unreadable) {
                plan.outputs.push(out);
            }
        }
    }
    plan.unreadable = unreadable;
    plan
}

/// Read one k9s file. A file that exists but cannot be read or parsed is
/// reported and recorded in `unreadable`.
fn read<T: for<'de> Deserialize<'de>>(
    path: &Path,
    skipped: &mut Vec<String>,
    unreadable: &mut Vec<PathBuf>,
) -> Option<T> {
    let text = match std::fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return None,
        Err(e) => {
            skipped.push(format!("{}: {e}", path.display()));
            unreadable.push(path.to_path_buf());
            return None;
        }
    };
    if text.trim().is_empty() {
        return None;
    }
    match serde_yaml::from_str(&text) {
        Ok(value) => Some(value),
        Err(e) => {
            skipped.push(format!("{}: {e}", path.display()));
            unreadable.push(path.to_path_buf());
            None
        }
    }
}

fn yaml_files(dir: &Path) -> Vec<PathBuf> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut paths: Vec<PathBuf> = entries
        .filter_map(|e| e.ok().map(|e| e.path()))
        .flat_map(|path| {
            if path.is_dir() {
                yaml_files(&path)
            } else if matches!(
                path.extension().and_then(|s| s.to_str()),
                Some("yaml" | "yml")
            ) {
                vec![path]
            } else {
                Vec::new()
            }
        })
        .collect();
    paths.sort();
    paths
}

/// Read one k9s plugin file in any of its three shapes: a `plugins:` map, a
/// bare map of plugins, or a single plugin named after the file.
fn read_plugins(
    path: &Path,
    skipped: &mut Vec<String>,
    unreadable: &mut Vec<PathBuf>,
) -> Vec<(String, K9sPlugin)> {
    let Some(value) = read::<serde_yaml::Value>(path, skipped, unreadable) else {
        return Vec::new();
    };
    let parse = |name: &str, v: serde_yaml::Value, skipped: &mut Vec<String>| {
        match serde_yaml::from_value::<K9sPlugin>(v) {
            Ok(p) => Some((name.to_string(), p)),
            Err(e) => {
                skipped.push(format!("plugin {name:?} in {}: {e}", path.display()));
                None
            }
        }
    };
    let Some(map) = value.as_mapping() else {
        skipped.push(format!("{}: not a mapping", path.display()));
        return Vec::new();
    };
    if map.contains_key("shortCut") {
        let name = path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or("plugin");
        return parse(name, value.clone(), skipped).into_iter().collect();
    }
    let map = match map.get("plugins") {
        Some(serde_yaml::Value::Mapping(inner)) => inner.clone(),
        Some(_) => return Vec::new(),
        None => map.clone(),
    };
    map.into_iter()
        .filter_map(|(k, v)| parse(k.as_str()?, v, skipped))
        .collect()
}

fn subdirs(dir: &Path) -> Vec<PathBuf> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut dirs: Vec<PathBuf> = entries
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.is_dir())
        .collect();
    dirs.sort();
    dirs
}

fn context_dirs(clusters: &Path) -> Vec<(String, String, PathBuf)> {
    let name = |p: &Path| p.file_name().map(|s| s.to_string_lossy().into_owned());
    let mut found = Vec::new();
    for cluster in subdirs(clusters) {
        for context in subdirs(&cluster) {
            if let (Some(c), Some(x)) = (name(&cluster), name(&context)) {
                found.push((c, x, context));
            }
        }
    }
    found
}

