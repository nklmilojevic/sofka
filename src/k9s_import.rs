struct ContextInput<'a> {
    cluster: &'a str,
    context: &'a str,
    dir: &'a Path,
    read_only: bool,
    skin: Option<&'a str>,
    bookmarks: Option<&'a Value>,
}

fn convert_context(
    ctx: &ContextInput,
    skipped: &mut Vec<String>,
    unreadable: &mut Vec<PathBuf>,
) -> Option<Output> {
    let mut doc = Table::new();
    let mut notes = Vec::new();
    if let Some(file) = read::<ContextFile>(&ctx.dir.join("config.yaml"), &mut notes, unreadable) {
        let k = file.k9s;
        if let Some(ro) = k.read_only
            && ro != ctx.read_only
        {
            doc.insert("readonly".into(), ro.into());
        }
        if let Some(name) = k
            .skin
            .as_deref()
            .filter(|s| !s.is_empty() && Some(*s) != ctx.skin)
        {
            match skin(name) {
                Some((sofka, _)) => {
                    table(&mut doc, "skin").insert("name".into(), sofka.into());
                }
                None => notes.push(format!("skin {name:?}: no sofka equivalent")),
            }
        }
        // Unless `lockFavorites` is set, k9s rewrites `favorites` with the
        // namespaces visited last: history, not a pinned list. `all` is a
        // pseudo-namespace.
        let favorites: Vec<Value> = k
            .namespace
            .favorites
            .iter()
            .filter(|_| k.namespace.lock_favorites)
            .filter(|ns| !matches!(ns.as_str(), "" | "all"))
            .map(|ns| Value::from(ns.as_str()))
            .collect();
        if !favorites.is_empty() {
            doc.insert("favorite_namespaces".into(), Value::Array(favorites));
        }
    }
    // Aliases that name a destination and hotkeys both become bookmarks.
    let mut local = Table::new();
    if let Some(file) = read::<AliasFile>(&ctx.dir.join("aliases.yaml"), &mut notes, unreadable) {
        convert_aliases(&file.entries(), &mut local, &mut notes);
    }
    if let Some(aliases) = local.remove("aliases") {
        doc.insert("aliases".into(), aliases);
    }
    let plugins = read_plugins(&ctx.dir.join("plugins.yaml"), &mut notes, unreadable);
    convert_plugins(&plugins, &mut doc, &mut notes);
    if doc.contains_key("plugins") {
        doc.insert("plugins_merge".into(), "name".into());
    }
    if let Some(file) = read::<HotkeyFile>(&ctx.dir.join("hotkeys.yaml"), &mut notes, unreadable) {
        convert_hotkeys(&file.hot_keys, &mut local, &mut notes);
    }
    if let Some(Value::Array(own)) = local.remove("bookmarks") {
        // A bookmarks list in an override replaces the inherited one; k9s
        // adds context hotkeys to the global ones, so carry both.
        let mut all = match ctx.bookmarks {
            Some(Value::Array(inherited)) => inherited.clone(),
            _ => Vec::new(),
        };
        all.extend(own);
        doc.insert("bookmarks".into(), Value::Array(all));
    }
    let label = format!("context {:?} on cluster {:?}", ctx.context, ctx.cluster);
    skipped.extend(notes.into_iter().map(|n| format!("{label}: {n}")));
    if doc.is_empty() {
        return None;
    }
    Some(Output {
        path: PathBuf::from("clusters")
            .join(crate::config::sanitize(ctx.cluster))
            .join(crate::config::sanitize(ctx.context))
            .join("config.yaml"),
        doc,
        label,
    })
}

