fn convert_settings(k: &Settings, doc: &mut Table, skipped: &mut Vec<String>) {
    if k.read_only == Some(true) {
        doc.insert("readonly".into(), true.into());
    }
    if let Some(view) = k.default_view.as_deref().map(str::trim)
        && !view.is_empty()
    {
        doc.insert("default_resource".into(), alias_target(view).into());
    }
    if k.ui.enable_mouse == Some(true) {
        doc.insert("mouse".into(), true.into());
    }
    if k.ui.headless == Some(true) {
        doc.insert("hide_header".into(), true.into());
    }
    if let Some(name) = k.ui.skin.as_deref().filter(|s| !s.is_empty()) {
        match skin(name) {
            Some((sofka, exact)) => {
                if !exact {
                    skipped.push(format!(
                        "skin {name:?}: no exact sofka match, using {sofka:?}"
                    ));
                }
                table(doc, "skin").insert("name".into(), sofka.into());
            }
            None => skipped.push(format!(
                "skin {name:?}: no sofka equivalent, keeping automatic dark/light detection (`:skin` lists the built-in skins)"
            )),
        }
    }

    let mut logs = Table::new();
    if let Some(tail) = k.logger.tail.filter(|t| *t != K9S_LOG_TAIL) {
        logs.insert("tail".into(), tail.into());
    }
    if let Some(buffer) = k.logger.buffer.filter(|b| *b != K9S_LOG_BUFFER && *b > 0) {
        logs.insert("buffer".into(), buffer.into());
    }
    if let Some(since) = k
        .logger
        .since_seconds
        .filter(|s| *s != K9S_LOG_SINCE && *s > 0)
    {
        logs.insert("since".into(), format!("{since}s").into());
    }
    if k.ui.defaults_to_full_screen == Some(true) {
        logs.insert("fullscreen".into(), true.into());
    }
    if !logs.is_empty() {
        doc.insert("logs".into(), Value::Table(logs));
    }

    let cpu = k.thresholds.cpu.unwrap_or(K9S_BAND);
    let memory = k.thresholds.memory.unwrap_or(K9S_BAND);
    let chosen = if cpu != K9S_BAND { cpu } else { memory };
    if chosen != K9S_BAND {
        if cpu != memory {
            let (used, other) = if cpu != K9S_BAND {
                ("CPU", "memory")
            } else {
                ("memory", "CPU")
            };
            skipped.push(format!(
                "thresholds: sofka has one utilization band for CPU and memory; used the {used} values, not the {other} values"
            ));
        }
        let mut band = Table::new();
        if let Some(warn) = chosen.warn {
            band.insert("warn".into(), warn.into());
        }
        if let Some(critical) = chosen.critical {
            band.insert("critical".into(), critical.into());
        }
        table(doc, "thresholds").insert("utilization".into(), Value::Table(band));
    }

    if let Some(image) = k.shell_pod.as_ref().and_then(|s| s.image.as_deref())
        && !image.is_empty()
        && !image.starts_with("busybox")
    {
        skipped.push(format!(
            "shellPod image {image:?}: set it as the node debug image under [debug] by hand"
        ));
    }
    if k.image_scans.as_ref().is_some_and(|s| s.enable) {
        skipped.push("imageScans: sofka has no image vulnerability scanning".into());
    }
    if let Some(addr) = k.port_forward_address.as_deref()
        && !matches!(addr, "" | "localhost" | "127.0.0.1")
    {
        skipped.push(format!(
            "portForwardAddress {addr:?}: sofka port-forwards bind to localhost"
        ));
    }
}

/// Map a k9s skin name onto a sofka built-in skin. The flag is false when the
/// match is a close relative rather than the same palette.
fn skin(name: &str) -> Option<(String, bool)> {
    let name = name.trim().to_ascii_lowercase();
    let name = name.strip_suffix(".yaml").unwrap_or(&name);
    let base = name.strip_suffix("-transparent").unwrap_or(name);
    if crate::theme::builtin(base).is_some() {
        return Some((base.to_string(), true));
    }
    let close = match base {
        "gruvbox-dark-hard"
        | "gruvbox-material-dark-hard"
        | "gruvbox-material-dark-medium"
        | "gruvbox-material-dark-soft" => "gruvbox-dark",
        "gruvbox-light-hard"
        | "gruvbox-material-light-hard"
        | "gruvbox-material-light-medium"
        | "gruvbox-material-light-soft" => "gruvbox-light",
        "rose-pine-moon" => "rose-pine",
        "tokyonight" | "tokyonight-night" | "tokyonight-storm" | "tokyo-night-storm" => {
            "tokyo-night"
        }
        "solarized-16" => "solarized-dark",
        _ => return None,
    };
    Some((close.to_string(), false))
}

fn table<'a>(doc: &'a mut Table, key: &str) -> &'a mut Table {
    doc.entry(key)
        .or_insert_with(|| Value::Table(Table::new()))
        .as_table_mut()
        .expect("importer tables are only created here")
}

