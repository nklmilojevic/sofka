fn convert_views(views: &BTreeMap<String, View>, doc: &mut Table, skipped: &mut Vec<String>) {
    for (key, view) in views {
        let mut columns = Vec::new();
        for spec in &view.columns {
            match column(key, spec) {
                Ok(Some(col)) => columns.push(Value::Table(col)),
                Ok(None) => {}
                Err(e) => skipped.push(format!("view {key:?} column {spec:?}: {e}")),
            }
        }
        let mut out = Table::new();
        if let Some(sort) = view.sort_column.as_deref().filter(|s| !s.is_empty()) {
            out.insert("sort".into(), sort.into());
        }
        if !columns.is_empty() {
            out.insert("replace".into(), true.into());
            out.insert("columns".into(), Value::Array(columns));
        }
        if !out.is_empty() {
            table(doc, "views").insert(key.clone(), Value::Table(out));
        }
    }
}

/// Convert one k9s column spec, `NAME[:jsonpath][|FLAGS]`. Hidden columns
/// (`H`) are dropped, which is what hiding means in a replaced view.
fn column(view: &str, spec: &str) -> Result<Option<Table>, String> {
    use std::sync::LazyLock;
    static RX: LazyLock<regex::Regex> = LazyLock::new(|| {
        regex::Regex::new(r"^([\w\s%/-]+):?([\w\W]*?)\|?([NTWSLRH]{0,3})$").expect("valid regex")
    });
    let caps = RX.captures(spec.trim()).ok_or("not a k9s column spec")?;
    let name = caps[1].trim().to_string();
    let path = caps[2].trim();
    let flags = &caps[3];
    if flags.contains('H') {
        return Ok(None);
    }
    let mut col = Table::new();
    col.insert("name".into(), name.clone().into());
    if path.is_empty() {
        match metric(view, &name) {
            Some(m) => col.insert("metric".into(), m.into()),
            None => col.insert("builtin".into(), name.into()),
        };
    } else {
        let pointer = json_pointer(path).ok_or_else(|| {
            format!(
                "JSONPath {path:?} needs filters or wildcards, which sofka columns do not support"
            )
        })?;
        col.insert("path".into(), pointer.into());
        if flags.contains('T') {
            col.insert("type".into(), "time".into());
        } else if flags.contains('N') {
            col.insert("type".into(), "number".into());
        }
    }
    if flags.contains('W') {
        col.insert("wide".into(), true.into());
    }
    if flags.contains('R') || flags.contains('N') {
        col.insert("align".into(), "right".into());
    } else if flags.contains('L') {
        col.insert("align".into(), "left".into());
    }
    Ok(Some(col))
}

/// k9s metric column headers and the sofka metric source behind each.
fn metric(view: &str, header: &str) -> Option<&'static str> {
    let nodes = view.ends_with("nodes") || view == "no" || view == "node";
    Some(match (nodes, header) {
        (true, "%CPU") => "node-cpu-utilization",
        (true, "%MEM") => "node-memory-utilization",
        (true, "CPU/R" | "%CPU/R") => "node-cpu-request",
        (true, "MEM/R" | "%MEM/R") => "node-memory-request",
        (true, "CPU/L" | "%CPU/L") => "node-cpu-limit",
        (true, "MEM/L" | "%MEM/L") => "node-memory-limit",
        (_, "CPU") => "cpu",
        (_, "MEM") => "memory",
        (false, "CPU/R") => "cpu-request",
        (false, "MEM/R") => "memory-request",
        (false, "CPU/L") => "cpu-limit",
        (false, "MEM/L") => "memory-limit",
        (false, "%CPU/R") => "cpu-request-utilization",
        (false, "%MEM/R") => "memory-request-utilization",
        (false, "%CPU/L") => "cpu-limit-utilization",
        (false, "%MEM/L") => "memory-limit-utilization",
        _ => return None,
    })
}

/// Convert a simple JSONPath (`.spec.containers[0].image`,
/// `{.metadata.labels['app\.kubernetes\.io/name']}`) into a JSON Pointer.
/// Filters, wildcards, slices, and recursive descent have no pointer form.
fn json_pointer(path: &str) -> Option<String> {
    let s = path.trim();
    let s = s
        .strip_prefix('{')
        .and_then(|s| s.strip_suffix('}'))
        .unwrap_or(s)
        .trim();
    let s = s.strip_prefix('$').unwrap_or(s);
    let s = s.strip_prefix('.').unwrap_or(s);
    if s.is_empty() {
        return None;
    }
    let mut segments = Vec::new();
    let mut seg = String::new();
    let mut after_bracket = false;
    let mut chars = s.chars();
    while let Some(c) = chars.next() {
        match c {
            '\\' => seg.push(chars.next()?),
            '.' => {
                if seg.is_empty() {
                    if !after_bracket {
                        return None;
                    }
                } else {
                    segments.push(std::mem::take(&mut seg));
                }
                after_bracket = false;
            }
            '[' => {
                if !seg.is_empty() {
                    segments.push(std::mem::take(&mut seg));
                }
                let mut raw = String::new();
                let mut quote = None;
                loop {
                    let ch = chars.next()?;
                    match (quote, ch) {
                        (None, ']') => break,
                        (None, '\'' | '"') => quote = Some(ch),
                        (Some(q), ch) if ch == q => quote = None,
                        _ => {}
                    }
                    raw.push(ch);
                }
                let raw = raw.trim();
                let inner = if let Some(key) = raw
                    .strip_prefix('\'')
                    .and_then(|r| r.strip_suffix('\''))
                    .or_else(|| raw.strip_prefix('"').and_then(|r| r.strip_suffix('"')))
                {
                    key.replace('\\', "")
                } else if !raw.is_empty() && raw.chars().all(|c| c.is_ascii_digit()) {
                    raw.to_string()
                } else {
                    return None;
                };
                if inner.is_empty() {
                    return None;
                }
                segments.push(inner);
                after_bracket = true;
            }
            '*' | '?' | '@' | '(' | ')' | ',' | ':' | ' ' | '$' => return None,
            _ => {
                if after_bracket {
                    return None;
                }
                seg.push(c);
            }
        }
    }
    if !seg.is_empty() {
        segments.push(seg);
    }
    if segments.is_empty() {
        return None;
    }
    Some(
        segments
            .iter()
            .map(|s| format!("/{}", s.replace('~', "~0").replace('/', "~1")))
            .collect(),
    )
}

